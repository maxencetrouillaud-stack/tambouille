await d1.p.evaluate(() => { UI.ptab = 'compte'; location.hash = 'profil'; render(); });
await d1.p.fill('#pfF', 'Testeur'); await d1.p.click('form[data-form=profileSave] button[type=submit]'); await d1.p.waitForTimeout(1500);
const { data: prof } = await ua.from('profiles').select('first_name').eq('id', sa.user.id).single();
check('modification du profil', prof?.first_name === 'Testeur');
