import { chromium } from 'playwright';
import { createClient } from '@supabase/supabase-js';
const SB_URL = 'https://ufqdplmibnczqnpmkgjq.supabase.co', SB_KEY = 'sb_publishable_UVBJjovoii0HKOGJ5KmqaQ_-PDzRq5i';
const A = { email: process.env.T1_EMAIL, pw: process.env.T1_PW }, B = { email: process.env.T2_EMAIL, pw: process.env.T2_PW };
const base = 'http://localhost:8080/', results = [], errors = [];
const check = (name, ok, extra = '') => { results.push(`${ok ? 'OK ' : 'ÉCHEC'} ${name}${extra ? ' — ' + extra : ''}`); if (!ok) process.exitCode = 1; };
const browser = await chromium.launch();
async function device(u, name) {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } }); const p = await ctx.newPage();
  p.on('pageerror', e => errors.push(`${name}: ${e.message}`));
  await p.goto(base + '#profil'); await p.waitForFunction(() => typeof SB !== 'undefined' && SB.client, null, { timeout: 15000 });
  await p.click('[data-act=ptab][data-v=compte]'); await p.fill('#liE', u.email); await p.fill('#liP', u.pw);
  await p.click('form[data-form=login] button[type=submit]');
  await p.waitForFunction(() => SB.user && UI.sync === 'ok', null, { timeout: 20000 });
  return { ctx, p };
}
